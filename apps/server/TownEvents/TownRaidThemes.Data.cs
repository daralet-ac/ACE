/// <summary>
/// A kind of raid: the raiders that march on a town, the beasts they bring as pets (none for most), and who leads them. Each is
/// a ladder of creatures from the low tiers to the high: a town gets the ones nearest its tier, scaled to it
/// (TownRaidThemes.Pick).
/// </summary>
/// <param name="Name">What the warning calls them: "Scouts report a Lugian war band massing..."</param>
/// <param name="Raiders">Who raids: people, the tool-using races, the undead and the other thinking things. Never beasts.</param>
/// <param name="Pets">Beasts and constructs the raiders bring, from a wave's smaller share</param>
/// <param name="Leaders">The Warlord's candidates; without one the highest-level raider leads</param>
/// <param name="Names">Creatures borrowed under another name, such as a dungeon's Artificer as a Conjurer</param>
public sealed record TownRaidTheme(string Name, uint[] Raiders, uint[] Pets, uint[] Leaders, IReadOnlyDictionary<uint, string> Names);

